def shelf(id_: str, title: str, hint: str, cards: list[str], more: str = "") -> str:
    if not cards:
        return ""
    more_html = f'<a class="more" href="{more}">Explore all →</a>' if more else ""
    return f"""<section class="shelf" id="{e(id_)}">
  <div class="shelf-head"><h2>{e(title)}</h2><span class="hint">{e(hint)}</span>{more_html}</div>
  <div class="rail">{''.join(cards)}</div>
</section>
"""


