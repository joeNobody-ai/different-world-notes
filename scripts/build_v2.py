import argparse
import html
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "v2"
ART = "assets/art"          # written relative to the site root, prefixed in the page
ASSETS = "../assets"

sys.path.insert(0, str(ROOT / "scripts"))
from build_pages import load, e, SOURCES, SOURCE_LABELS, render_glossary  # noqa: E402

TAG_RED = '<span class="badge">'


def art(name: str) -> str:
    return f"{ASSETS}/art/{name}"


def src_line(keys: list[str]) -> str:
    out = []
    for k in keys:
        url = SOURCES.get(k)
        label = SOURCE_LABELS.get(k, k).split(":")[0]
        out.append(f'<a href="{e(url)}" rel="noopener">{e(label)}</a>' if url else e(label))
    return " · ".join(out)


def head(title: str, desc: str) -> str:
    return f"""<!doctype html>
<html lang="en" class="v2">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{e(title)}</title>
<meta name="description" content="{e(desc)}">
<meta name="color-scheme" content="dark">
<link rel="stylesheet" href="{ASSETS}/v2/netflix.css">
<link rel="icon" href="{art('logo.svg')}">
</head>
<body>
"""


