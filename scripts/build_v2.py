"""build_v2.py — render the V2 "browse" pages: a Netflix-style skin over the same content.

Same data as V1 (data/*.json), different presentation:
    V2/index.html      billboard + horizontal shelves (episodes, top callbacks, cast, the 1987 era,
                       politics, the real campuses) + method
    V2/ep01..ep10.html episode detail pages: backdrop, synopsis, callbacks as episode rows, the
                       politics and script panels (collapsed), next-episode card

Images
    assets/art/*.svg        generated by scripts/make_art.py — our own artwork, committed
    assets/img/commons/*    freely-licensed Commons photos with printed credits, committed
    IMDb CDN key art        HOTLINKED ONLY (never downloaded, never committed) with generated art
                            layered behind it as the fallback. Disable with --no-poster.

Usage:  python3 scripts/build_v2.py [--no-poster]
"""
