def top_callback_cards(callbacks: dict, episodes_by_num: dict) -> list[str]:
    weight = {"title-echo": 6, "cast": 5, "lore": 4, "theme": 3, "reading": 2}
    conf = {"verified": 3, "likely": 2, "interpretation": 1}
    scored = sorted(
        callbacks["callbacks"],
        key=lambda c: -(weight.get(c["tier"], 0) + conf.get(c["confidence"], 0)),
    )
    picked, per_ep = [], {}
    for c in scored:
        if per_ep.get(c["episode"], 0) >= 2:
            continue
        picked.append(c)
        per_ep[c["episode"]] = per_ep.get(c["episode"], 0) + 1
        if len(picked) == 10:
            break
    cards = []
    for i, c in enumerate(picked, 1):
        ep = episodes_by_num[c["episode"]]
        o = c["origin"]
        cards.append(f"""<a class="card rank" href="ep{c['episode']:02d}.html#{e(c['id'])}">
  <img class="still" src="{art(f"ep{c['episode']:02d}.svg")}" alt="" loading="lazy">
  <span class="rankno">{i}</span>
  <div class="body">
    <div class="row1"><span class="num">EPISODE {c['episode']}</span>
      <span class="badge {e(c['confidence'])}">{e(c['confidence'])}</span>
      <span class="badge">{e(c['tier'])}</span></div>
    <h3>{e(c['scene_2026'][:78])}{'…' if len(c['scene_2026']) > 78 else ''}</h3>
    <p class="desc">from S{o['season']}·E{o['episode']} “{e(o['title'])}” ({e(o['air_date'])})</p>
  </div>
</a>""")
    return cards


def cast_cards(characters: dict, headshots: dict) -> list[str]:
    cards = []
    for group in ("main", "special_guest"):
        for p in characters.get(group, []):
            slug = re.sub(r"[^a-z0-9]+", "-", p["name_2026"].lower()).strip("-")
            shot = headshots.get(p["actor"])
            img = (f'<img src="{e(shot)}" alt="{e(p["actor"])}" loading="lazy" '
                   f'onerror="this.style.display=\'none\'">') if shot else ""
            returning = p.get("name_original")
            cards.append(f"""<a class="card cast" href="../index.html#who">
  <div style="position:relative">{img}
    <img src="{art(f'cast-{slug}.svg')}" alt="" style="position:{"absolute;inset:0" if img else "static"};z-index:{-1 if img else 0}">
  </div>
  <div class="body">
    <h3>{e(p['name_2026'])}</h3>
    <p class="desc">{e(p['actor'])}</p>
    <div class="tags">
      <span>{e(p['role_2026'])}</span>
      {f'<span>in 1987: {e(returning)}</span>' if returning else '<span>new character</span>'}
    </div>
  </div>
</a>""")
    return cards


